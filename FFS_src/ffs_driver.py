def parse_scalar(text: str) -> Any:
    value = text.strip()
    if not value:
        return None
    low = value.lower()
    if low in ('null', 'none', '~'):
        return None
    if low in ('true', 'yes', 'on'):
        return True
    if low in ('false', 'no', 'off'):
        return False
    if value.startswith('[') and value.endswith(']'):
        inner = value[1:-1].strip()
        if not inner:
            return []
        return [parse_scalar(part.strip()) for part in inner.split(',')]
    try:
        if any(mark in value for mark in ('.', 'e', 'E')):
            return float(value)
        return int(value)
    except ValueError:
        return value.strip('\'')


def load_yaml(path: Path) -> dict[str, Any]:
    try:
        import yaml  # type: ignore
    except Exception:
        yaml = None
    if yaml is not None:
        with path.open('r', encoding='utf-8') as handle:
            data = yaml.safe_load(handle)
        return data or {}

    root: dict[str, Any] = {}
    stack: list[tuple[int, dict[str, Any]]] = [(-1, root)]
    for raw in path.read_text(encoding='utf-8').splitlines():
        if not raw.strip() or raw.lstrip().startswith('#'):
            continue
        line = raw.split('#', 1)[0].rstrip()
        if not line.strip():
            continue
        indent = len(line) - len(line.lstrip(' '))
        key, sep, value = line.strip().partition(':')
        if not sep:
            raise ValueError(f'Cannot parse yaml line: {raw}')
        while stack and indent <= stack[-1][0]:
            stack.pop()
        parent = stack[-1][1]
        if value.strip() == '':
            child: dict[str, Any] = {}
            parent[key] = child
            stack.append((indent, child))
        else:
            parent[key] = parse_scalar(value)
    return root


def as_path(base: Path, value: str | Path) -> Path:
    path = Path(value)
    return path if path.is_absolute() else base / path


def require_file(path: Path, label: str) -> Path:
    if not path.exists():
        raise FileNotFoundError(f'{label} does not exist: {path}')
    return path


def read_key_value_cfg(path: Path) -> dict[str, str]:
    data: dict[str, str] = {}
    for raw in path.read_text(encoding='utf-8').splitlines():
        line = raw.split('#', 1)[0].strip()
        if not line or ':' not in line:
            continue
        key, value = line.split(':', 1)
        data[key.strip()] = value.strip()
    return data


def write_gas_cfg(base_cfg: Path, output: Path, overrides: dict[str, Any]) -> None:
    text = base_cfg.read_text(encoding='utf-8').rstrip() + '\n'
    text += '\n# FFS runtime overrides generated by FFS_src/ffs_driver.py\n'
    for key, value in overrides.items():
        if isinstance(value, bool):
            rendered = 'true' if value else 'false'
        else:
            rendered = str(value)
        text += f'{key}: {rendered}\n'
    output.write_text(text, encoding='utf-8')



def format_temperature(value: float) -> str:
    return str(int(value)) if float(value).is_integer() else f'{value:g}'

def is_float_token(value: str) -> bool:
    try:
        float(value)
        return True
    except ValueError:
        return False

def rewrite_temperature_line(raw: str, temperature_K: float | None, velocity_seed: int | None) -> str:
    if temperature_K is None and velocity_seed is None:
        return raw
    prefix = raw[:len(raw) - len(raw.lstrip())]
    body = raw.strip()
    if not body or body.startswith('#'):
        return raw
    command, sep, comment = body.partition('#')
    parts = command.split()
    if not parts:
        return raw
    temperature = format_temperature(temperature_K) if temperature_K is not None else None
    changed = False
    if parts[0] == 'velocity' and len(parts) >= 2:
        if temperature is not None:
            parts[1] = temperature
            changed = True
        if velocity_seed is not None:
            if len(parts) >= 4 and parts[2] == 'seed':
                parts[3] = str(velocity_seed)
            elif len(parts) == 2:
                parts.extend(['seed', str(velocity_seed)])
            else:
                return raw
            changed = True
    elif parts[0] == 'ensemble':
        if temperature is None:
            return raw
        if 'temp' in parts:
            idx = parts.index('temp')
            if idx + 2 < len(parts):
                parts[idx + 1] = temperature
                parts[idx + 2] = temperature
                changed = True
        elif len(parts) >= 4 and parts[1].startswith(('nvt', 'npt')) and is_float_token(parts[2]) and is_float_token(parts[3]):
            parts[2] = temperature
            parts[3] = temperature
            changed = True
        else:
            return raw
    else:
        return raw
    if not changed:
        return raw
    rewritten = prefix + ' '.join(parts)
    if sep:
        rewritten += ' #' + comment
    return rewritten

def render_run_in(
    template: Path,
    output: Path,
    monitor_model: str,
    monitor_cfg: str,
    max_steps: int,
    temperature_K: float | None,
    velocity_seed: int | None,
) -> None:
    lines: list[str] = []
    monitor_line = f'FFSampling {monitor_model} {monitor_cfg}'
    run_line = f'run {max_steps}'
    inserted_monitor = False
    inserted_run = False
    for raw in template.read_text(encoding='utf-8').splitlines():
        stripped = raw.strip()
        if not stripped:
            lines.append(raw)
            continue
        raw = rewrite_temperature_line(raw, temperature_K, velocity_seed)
        stripped = raw.strip()
        key = stripped.split()[0]
        if key in MONITOR_KEYS:
            continue
        if key == 'run':
            if not inserted_monitor:
                lines.append(monitor_line)
                inserted_monitor = True
            if not inserted_run:
                lines.append(run_line)
                inserted_run = True
            continue
        lines.append(raw)
    if not inserted_monitor:
        lines.append(monitor_line)
    if not inserted_run:
        lines.append(run_line)
    output.write_text('\n'.join(lines).rstrip() + '\n', encoding='utf-8')



def strip_extxyz_velocities(source: Path, target: Path) -> bool:
    lines = source.read_text(encoding='utf-8', errors='replace').splitlines()
    if len(lines) < 2:
        return False
    comment = lines[1]
    match = re.search(r'Properties=(["\'])(.*?)\1', comment)
    quoted = True
    if match:
        quote = match.group(1)
        spec = match.group(2)
    else:
        match = re.search(r'Properties=([^\s]+)', comment)
        if not match:
            return False
        quoted = False
        quote = ''
        spec = match.group(1)
    tokens = spec.split(':')
    if len(tokens) % 3 != 0:
        return False

    keep_indices: list[int] = []
    kept_properties: list[str] = []
    offset = 0
    removed = False
    for i in range(0, len(tokens), 3):
        name, value_type, count_text = tokens[i:i + 3]
        try:
            count = int(count_text)
        except ValueError:
            return False
        indices = list(range(offset, offset + count))
        offset += count
        if name.lower() in ('vel', 'velocity'):
            removed = True
            continue
        kept_properties.extend([name, value_type, count_text])
        keep_indices.extend(indices)
    if not removed:
        return False

    atom_lines: list[str] = []
    for raw in lines[2:]:
        parts = raw.split()
        if len(parts) < offset:
            return False
        atom_lines.append(' '.join(parts[i] for i in keep_indices))

    new_spec = ':'.join(kept_properties)
    if quoted:
        replacement = f'Properties={quote}{new_spec}{quote}'
    else:
        replacement = f'Properties={new_spec}'
    new_comment = comment[:match.start()] + replacement + comment[match.end():]
    target.write_text('\n'.join([lines[0], new_comment] + atom_lines) + '\n', encoding='utf-8')
    return True


def copy_start_model(source: Path, target: Path, resample_velocities: bool) -> bool:
    if resample_velocities and strip_extxyz_velocities(source, target):
        return True
    shutil.copy2(source, target)
    return False

def copy_inputs(files: list[Path], workdir: Path) -> None:
    for item in files:
        target = workdir / item.name
        if item.is_dir():
            if target.exists():
                shutil.rmtree(target)
            shutil.copytree(item, target)
        else:
            shutil.copy2(item, target)


def read_last_cv_log(path: Path) -> tuple[int, list[float], int]:
    if not path.exists():
        return 0, [], 0
    rows: list[list[float]] = []
    for raw in path.read_text(encoding='utf-8', errors='replace').splitlines():
        parts = raw.split()
        if not parts:
            continue
        try:
            rows.append([float(part) for part in parts])
        except ValueError:
            continue
    if not rows:
        return 0, [], 0
    last = rows[-1]
    status = int(round(last[0])) if last else 0
    return status, last[1:], len(rows)


def estimate_steps(cv_rows: int, cv_log_interval: int) -> int:
    if cv_rows <= 0:
        return 0
    return max(1, cv_rows - 1) * max(1, cv_log_interval)


def parse_completed_steps(stdout: str) -> int:
    matches = re.findall(r'(\d+)\s+steps completed\.', stdout)
    return int(matches[-1]) if matches else 0


def safe_name(prefix: str, index: int) -> str:
    return f'{prefix}_{index:06d}'


def read_template_run_steps(template: Path, default: int = 10000) -> int:
    for raw in template.read_text(encoding='utf-8').splitlines():
        stripped = raw.strip()
        if not stripped or stripped.startswith('#'):
            continue
        parts = stripped.split()
        if parts and parts[0] == 'run' and len(parts) > 1:
            try:
                return int(parts[1])
            except ValueError:
                break
    return default


def normalize_interface_steps(value: Any, count: int, default: int) -> list[int]:
    if value is None:
        return [default for _ in range(count)]
    if isinstance(value, list):
        steps = [int(item) for item in value]
        if len(steps) == 1:
            return steps * count
        if len(steps) != count:
            raise ValueError('ffs.interface_max_steps must be an integer or have len(interfaces)-1 entries')
        return steps
    return [int(value) for _ in range(count)]


